"""Write LOCAL_VERIFICATION.md from measured evidence (nothing typed in by hand).

    python scripts/model_inventory.py && python scripts/scan_network.py && python -m pytest tests/test_offline.py
    python scripts/local_verification.py

Sources: outputs/model_inventory.json, outputs/eval/network_scan.json, outputs/logs/offline_test.json,
outputs/logs/energy.csv, the latest run reports, and the live Python environment.
"""
from __future__ import annotations

import datetime as dt
import json
import platform
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
import bluesight  # noqa: E402,F401
from bluesight.config import ROOT, load_config, resolve_device  # noqa: E402
from bluesight.pipeline import hardware_string  # noqa: E402


def j(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def main() -> None:
    cfg = load_config()
    inv = j(ROOT / "outputs" / "model_inventory.json")
    scan = j(ROOT / "outputs" / "eval" / "network_scan.json")
    off = j(ROOT / "outputs" / "logs" / "offline_test.json")
    en = pd.read_csv(ROOT / "outputs" / "logs" / "energy.csv") if (ROOT / "outputs" / "logs" / "energy.csv").exists() else None
    import torch

    dev = resolve_device(cfg)
    reports = []
    for f in sorted((ROOT / "outputs" / "runs").rglob("report.json")):
        r = json.loads(f.read_text())
        if r.get("network"):
            reports.append(r)
    L = ["# LOCAL VERIFICATION: how we know BlueSight runs on this computer", "",
         f"_Generated by `scripts/local_verification.py` on {dt.datetime.now().isoformat(timespec='seconds')} from measured evidence. "
         "Re-run it to refresh._", "",
         "## In one paragraph", "",
         "BlueSight is a program that runs entirely on the laptop in front of you. The survey video is read from this "
         "computer's disk, the two AI models (one finds moving organisms, one recognises species) are files stored in "
         "this project folder, and every result is written back to this folder. No video, image or result is sent "
         "anywhere, and no online AI service (such as ChatGPT, Claude, Google or Hugging Face's hosted inference) is used. "
         "We don't just claim this: the program counts every attempt to reach the internet while it works, an automated "
         "test runs the whole analysis with the internet blocked, and the code was searched for anything that could connect out.", "",
         "## How BlueSight runs locally, step by step", "",
         "1. **You start the app** with `streamlit run app/streamlit_app.py`. It opens in your web browser at "
         "`http://localhost:8501`. *localhost* means \"this computer\": the app is configured to accept connections only "
         "from this machine, and Streamlit's usage statistics are switched off.",
         "2. **You pick a video.** It's read straight from the disk (`data/videos/` or `outputs/uploads/`). Uploading in the "
         "app copies the file into the project folder on the same computer; nothing leaves the machine.",
         "3. **Enhance.** Ordinary image processing (OpenCV) corrects the green cast and boosts contrast, and scores visibility. No AI.",
         "4. **Detect.** BlueSight's motion detector compares each frame with the still background around it. It uses "
         "OpenCV and PyTorch on this computer's GPU. It has no trained weights, so there's nothing to download.",
         "5. **Track.** ByteTrack (from the `supervision` library) follows each fish from frame to frame so it's counted once.",
         "6. **Identify.** BioCLIP, a biology image model, turns each fish's best views into a list of numbers that are "
         "compared with the reference images of every species in the registry. BioCLIP's weights are a file in "
         "`models/hf/` that was downloaded once; on start-up BlueSight switches the model library to offline mode, so it "
         "can't download or check for updates.",
         "7. **Count and flag.** MeanCount and MaxN are computed following Coastal Action's protocol. Anything unfamiliar "
         "goes to the review queue.",
         "8. **Review.** Your decisions are saved in a local database file (`outputs/bluesight.db`).",
         "9. **Throughout steps 3–7, the network guard is on.** It watches every outgoing connection. Connections inside "
         "this computer are allowed; anything else is blocked and counted. The count is saved with the results and shown "
         "on the app's **Model & privacy** page.", "",
         "## Where everything lives and what runs where", "",
         "| What | Where on disk | Loaded by | Runs on |", "|---|---|---|---|"]
    for m in (inv or {}).get("models", []):
        L.append(f"| {m['role']}: `{m['name']}`{'' if m['in_use'] else ' (installed, not used by default)'} | `{m['local_path']}` | "
                 f"{m['loaded_by']} | {m['runs_on']} |")
    for a in (inv or {}).get("algorithms", []):
        L.append(f"| {a['role']}: {a['name']} | `{a['local_path']}` | {a['loaded_by']} | {a['runs_on']} |")
    L += ["| Video, results, review decisions | `data/videos/`, `outputs/` (SQLite `outputs/bluesight.db`) | OpenCV, PyAV, sqlite3 | CPU |",
          "| The app | `app/` | Streamlit, bound to `localhost` | CPU (your browser shows it) |", "",
          f"This machine: **{hardware_string(dev)}**, PyTorch {torch.__version__}, Python {platform.python_version()}. "
          f"`device={dev}` means the models run on the "
          + {"mps": "Apple GPU (Metal Performance Shaders)", "cuda": "NVIDIA GPU (CUDA)", "cpu": "CPU"}.get(dev, dev) + ".", "",
          "## Data flow: the video never leaves the machine", "",
          "```mermaid", "flowchart LR",
          "  subgraph Laptop[\"This computer (no internet needed)\"]",
          "    V[(Survey video<br/>data/videos)] --> E[Enhance<br/>OpenCV]",
          "    E --> D[Detect<br/>motion detector<br/>PyTorch on GPU]",
          "    D --> T[Track<br/>ByteTrack]",
          "    T --> I[Identify<br/>BioCLIP weights<br/>from models/]",
          "    M[(Model files<br/>models/hf)] -.loaded from disk.-> I",
          "    R[(Species registry<br/>outputs/bluesight.db)] <--> I",
          "    I --> C[Count + flag]",
          "    C --> O[(Reports, clips<br/>outputs/)]",
          "    O --> UI[Streamlit app<br/>localhost:8501]",
          "    UI -->|your review decisions| R",
          "    G{{Network guard:<br/>counts and blocks<br/>outbound connections}} -.watches.-> E & D & T & I & C",
          "  end",
          "  Internet((Internet)) x--x|blocked, counted: 0| G",
          "```", "",
          "## Evidence", "",
          "### 1. Offline test (automated)", ""]
    if off:
        L += [f"`tests/test_offline.py` blocks every connection that isn't to this computer (it patches Python's socket "
              "functions itself, independently of BlueSight's guard), then runs the **full pipeline** from scratch on a short "
              "clip: a fresh registry, real detection, BioCLIP loaded from disk, identification, evidence clips and the report.", "",
              "| Result | Clip | Runtime | Frames / tracks | Blocked connection attempts | Network guard count | When |",
              "|---|---|---|---|---|---|---|",
              f"| **{'PASSED' if off['passed'] else 'FAILED'}** | {off['clip']} | {off['runtime_s']} s | {off['frames']} / {off['tracks']} | "
              f"{off['blocked_attempts']} | {off['guard']['external_connection_attempts']} | {off['when']} |", ""]
    else:
        L += ["Not run yet: `python -m pytest tests/test_offline.py -s`.", ""]
    L += ["**Repeat it by hand with Wi-Fi off:**", "",
          "1. Start the app once while online (optional; nothing is downloaded at start-up).",
          "2. Turn Wi-Fi off (menu bar → Wi-Fi → off) and unplug any network cable.",
          "3. `.venv/bin/streamlit run app/streamlit_app.py`, open http://localhost:8501.",
          "4. Analyze → *Custom window* → start 1280, length 75 → **Analyze video**. Then review an item in the Review queue and open "
          "the Species registry.",
          "5. Everything works. **Model & privacy** shows *0 external network calls during the last run*.",
          "6. Command-line equivalent: `.venv/bin/python -m pytest tests/test_offline.py -s` (passes with Wi-Fi off too).", "",
          "### 2. Network guard during real runs", "",
          "Every analysis records `network.external_connection_attempts` in its `report.json`.", "",
          "| Run | Generated | Mode | External attempts | Local connections | Runtime (s) |", "|---|---|---|---|---|---|"]
    for r in sorted(reports, key=lambda r: r["generated_at"])[-10:]:
        n = r["network"]
        L.append(f"| `{r['run_id']}` | {r['generated_at']} | {n['mode']} | **{n['external_connection_attempts']}** | "
                 f"{n['local_connections']} | {r['runtime_s']} |")
    L += ["", "### 3. Code scan", ""]
    if scan:
        L += [f"`scripts/scan_network.py` searched {', '.join('`' + t + '`' for t in scan['targets'])} for HTTP clients, raw sockets, "
              "hosted-AI SDKs, API keys, model-hub downloads, URLs and telemetry. "
              f"**{scan['summary']['hits']} matches, {scan['summary']['unexplained']} unexplained.**", "",
              "| Kind | Matches |", "|---|---|"] + [f"| {k} | {v} |" for k, v in scan["summary"]["kinds"].items()] + [""]
        L += ["What was found and what was done about it:", "",
              "| Found | Where | Status |", "|---|---|---|",
              "| Hugging Face model loading (`from_pretrained`, `create_model_and_transforms`) | `src/bluesight/embed.py`, `detect.py` | "
              "Loads from `models/` on disk. **Fixed in v2:** offline mode used to be set only in `load_config()`, but `huggingface_hub` "
              "reads it at import time, so it's now set in `bluesight/__init__.py` before anything else loads (plus `HF_HUB_DISABLE_TELEMETRY`). |",
              "| Streamlit usage statistics (on by default) | Streamlit | **Disabled:** `.streamlit/config.toml` `browser.gatherUsageStats = false`. |",
              "| Streamlit listening on all network interfaces (default) | Streamlit | **Restricted:** `server.address = \"localhost\"`. |",
              "| Streamlit 'Deploy' button (links to Streamlit Cloud) | Streamlit toolbar | **Hidden:** `client.toolbarMode = \"minimal\"`. |",
              "| 'Ask Google' / 'Ask ChatGPT' buttons on error messages (Streamlit default on localhost) | Streamlit error box | **Removed:** `client.showErrorLinks = false` (found while testing the app in v2). |",
              "| Web fonts | app CSS | **Not used:** system fonts only, so the browser never contacts a font server. |",
              "| `requests` / `httpx` / `urllib` calls, API keys, OpenAI/Anthropic/Google/Roboflow clients | project code | **None found.** |",
              "| CodeCarbon (energy estimate) | `src/bluesight/energy.py` | Uses `OfflineEmissionsTracker` only, which has no API. Verified: 0 connections under the guard. |",
              "| Playwright (screenshots) | `scripts/screenshot_app.py` | Development tool, talks to `localhost` only, not needed to run BlueSight. |", ""]
    L += ["### 4. Model inventory", ""]
    if inv:
        L += ["| Model | Role | Used by default | Version | Source (downloaded once) | Licence | Local path | Size on disk | SHA-256 of weights |",
              "|---|---|---|---|---|---|---|---|---|"]
        for m in inv["models"]:
            hashes = "<br>".join(f"`{w['file']}` `{w['sha256']}`" for w in m["all_weight_files"])
            L.append(f"| `{m['name']}` | {m['role']} | {'yes' if m['in_use'] else 'no'} | {m['version']} | {m['source']} | {m['licence']} | "
                     f"`{m['local_path']}` | {m['size_mb']} MB | {hashes} |")
        for a in inv["algorithms"]:
            L.append(f"| {a['name']} | {a['role']} | yes | {a['version']} | {a['loaded_by']} | {a['licence']} | `{a['local_path']}` | – | {a['weights']} |")
        L += ["", f"Inventory generated {inv['generated_at']}. Check a hash yourself: `shasum -a 256 <file>`.", ""]
    L += ["### 5. Hardware and energy", ""]
    if en is not None and len(en):
        e = en.dropna(subset=["energy_wh"])
        L += [f"Energy is estimated per run with CodeCarbon's **OfflineEmissionsTracker** (Nova Scotia grid carbon intensity). "
              "On this Mac it estimates CPU power from CPU load and RAM power from a model; **it can't see the Apple GPU**, "
              "so these figures are estimates and, for GPU-heavy runs, lower bounds.", "",
              "| Run | Detections reused from cache? | Runtime (s) | Energy (Wh) | CO2e (g) | External connections |", "|---|---|---|---|---|---|"]
        for r in e.tail(12).itertuples():
            L.append(f"| `{r.run_id}` | {'yes' if r.cached_detection else 'no (full processing)'} | {r.runtime_s} | {r.energy_wh:.3f} | {r.co2_g:.3f} | {r.external_connections} |")
        full = e[e.cached_detection == 0]
        if len(full):
            L += ["", "Runtime per minute of video for full (uncached) runs is in EVALUATION.md (§ processing time)."]
    else:
        L += ["No energy measurements yet."]
    L += ["", "## Limits of this verification (honest notes)", "",
          "* The network guard sees connections made by Python code inside BlueSight's process, which is where all the AI "
          "and video work happens. It can't see other programs on the computer. The Wi-Fi-off test covers everything.",
          "* Model weights were downloaded from Hugging Face **once**, during setup. That is the only network step, and it's "
          "documented in README.md.",
          "* Installing Python packages (`pip`/`uv`) needs the internet, once, like any software installation.",
          "* Energy numbers are estimates from CodeCarbon's models, not a power meter, and exclude the GPU.", ""]
    (ROOT / "LOCAL_VERIFICATION.md").write_text("\n".join(L))
    print("wrote LOCAL_VERIFICATION.md")


if __name__ == "__main__":
    main()
